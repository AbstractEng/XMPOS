export const USAGE_MACHINES = ["kit", "synth", "midi", "other", "sampler", "unselected"] as const;
export type UsagePage = (typeof USAGE_PAGES)[number];
export const USAGE_MAX_MS = 24 * 60 * 60 * 1000;
export function isUsagePage(page: string): page is UsagePage {
  return (USAGE_PAGES as readonly string[]).includes(page);
}
export function isUsageCounter(key: string) {
  const [kind, name, page, extra] = key.split(":");
  if (extra !== undefined) return false;
  if (kind === "control") return USAGE_BUTTONS.includes(name ?? "") && isUsagePage(page ?? "");
  if (page !== undefined) return false;
  if (kind === "feature") return (USAGE_FEATURES as readonly string[]).includes(name ?? "");
  return kind === "machine" && (USAGE_MACHINES as readonly string[]).includes(name ?? "");
}
