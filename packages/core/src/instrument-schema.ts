import { z } from "zod";
export const SynthPatchSchema = z
  .object({
    name: z.string().min(1).max(80),
    oscillator: z.enum(["sine", "saw", "square"]),
    attack: z.number().finite().min(0.001).max(2),
    decay: z.number().finite().min(0.001).max(2),
    sustain: z.number().finite().min(0).max(1),
    release: z.number().finite().min(0.005).max(2),
    cutoff: z.number().finite().min(30).max(16000),
    // Later, optional (at their defaults the synth plays as before): the filter's
    // resonance, the filter envelope (octaves it opens, seconds it closes in), a
    // second oscillator detuned in cents, and glide from the previous note.
    resonance: z.number().finite().min(0).max(1).optional(),
    "env-amount": z.number().finite().min(0).max(6).optional(),
    "env-decay": z.number().finite().min(0.01).max(2).optional(),
    detune: z.number().finite().min(0).max(50).optional(),
    glide: z.number().finite().min(0).max(1).optional(),
  })
  .strict();
export type SynthPatch = z.infer<typeof SynthPatchSchema>;
