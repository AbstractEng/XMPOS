"""Export the approved XMP mark for the Live's framebuffer painter."""

from pathlib import Path

from PIL import Image

brand = Path(__file__).resolve().parent
width, height = 88, 34
with Image.open(brand / "assets/png/xmp-orbit-2048.png") as source:
    logo = source.convert("RGBA").resize((width, height), Image.Resampling.BOX)

rows = []
for y in range(height):
    row = []
    for x in range(width):
        _, _, blue, opacity = logo.getpixel((x, y))
        # Ivory blue is 214 and gold blue is 133. The mark separates them with a transparent ring.
        coverage = (opacity * 127 + 127) // 255
        value = (0x80 if blue < 174 and coverage else 0) | coverage
        row.append(f"0x{value:02x}")
    for start in range(0, width, 16):
        rows.append("    " + ", ".join(row[start:start + 16]) + ",")

target = brand.parents[1] / "native/include/xmp/live_logo.hpp"
target.write_text(
    "// Generated by brand/xmp/render-touchscreen-logo.py from the approved XMP Orbit artwork.\n"
    "#pragma once\n\n"
    "#include <cstdint>\n\n"
    "namespace xmp::live::gfx::logo {\n"
    f"constexpr int kWidth = {width}, kHeight = {height};\n"
    "// The high bit picks ivory or gold. The low seven bits store opacity.\n"
    "constexpr std::uint8_t kPixels[kWidth * kHeight] = {\n"
    + "\n".join(rows)
    + "\n};\n}  // namespace xmp::live::gfx::logo\n",
    encoding="utf-8",
)
